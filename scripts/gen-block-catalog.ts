#!/usr/bin/env node
/**
 * gen-block-catalog —— 28 块清单生成器（ISS-900 / P3-F2，DOC-520 §四 F-2，照 F-1 形态新建）。
 *
 * 块清单是全项目最会变的表（28 种、逐批实现，DOC-512 §5.6.4 判「手维护必腐」）。本生成器
 * 读 `packages/kb/blocks/src/spec.ts` 的 zod discriminated union 骨架，把「有哪些块、各带什么
 * 显式字段、是不是容器/引用、属哪一档、是不是第一批」摊成 `docs/block-catalog.md`，消除
 * 「块清单只能读源码获得」这一环。
 *
 * 机制与 F-1（gen-field-catalog，ISS-896）同构，**失败驱动**：改 spec.ts → 忘跑生成器 →
 * `node scripts/gates/verify-block-catalog.ts --check` 红 → 跑生成器 → 提交。生成物进 git、
 * 不手改、重生成幂等（无时间戳）；判据不另写扫描，直接 import 本文件的 buildBlockCatalog。
 *
 * **抽取口径**（AST 不读正则——注释/字符串里的 `z.strictObject` 不是 AST 节点）：
 *   ① 一个块 = `const X = z.strictObject({ ...base("type"), <显式字段...> })`；
 *      `type` 取自 `base("…")` 的字符串参数（不是 schema 变量名）。没有 `...base(...)` 的
 *      `z.strictObject`（如共用的 `Rich`）天然不是块。
 *   ② 字段 = `base()` 展开之外的显式属性名（shorthand 与 `name: expr` 都收）；所有块共有的
 *      `id` + `type` 来自 `base()`，不重复列进字段列。
 *   ③ 分组/标记不硬编码进表：`A_BASIC_TYPES` / `B_BUSINESS_TYPES` / `C_NOTION_TYPES` 决定批次，
 *      `CONTAINER_TYPES` / `REFERENCE_TYPES` 决定两个标记——词表是分组的唯一真相源，改词表
 *      不改 schema（或反之）都会让生成物变、判据红。
 *   ④ 「第一批 14 种」是 ISS-532 钉死的业务口径（A 档 9 + B 档 5：issueRef/docRef/mermaid/
 *      toggle/view），不是从 spec.ts 推得出的，故作为常量写在 {@link FIRST_BATCH_B} 并注明出处。
 *
 * 用法：node scripts/gen-block-catalog.ts            # 重生成
 *       node scripts/gen-block-catalog.ts --check    # 只比对，旧了退出 1（与判据同口径）
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import ts from "typescript"

/** 仓库根（本文件在 `<repo>/scripts/`）。 */
export const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")

/** 数据源（块 schema 的唯一真相源）。 */
export const SOURCE_REL = "packages/kb/blocks/src/spec.ts"
/** 生成物。 */
export const OUT_REL = "docs/block-catalog.md"
/** 文件头逐字稳定，判据此校验（形态对齐 F-1 / D0）。 */
export const HEADER = "<!-- Generated by scripts/gen-block-catalog.ts — do not edit by hand. -->"

/**
 * 第一批 14 种里的 B 档 5 种（A 档 9 由 A_BASIC_TYPES 全量自动进第一批）。
 * 口径出处：ISS-532 正文「## 第一批清单钉死（14 种）」——A9 + issueRef/docRef/mermaid/toggle/view；
 * callout/table 留 P6，老板加第 15 种另立单。这里是有意的业务常量，不从 spec.ts 推导。
 */
export const FIRST_BATCH_B = ["issueRef", "docRef", "mermaid", "toggle", "view"] as const

const byCodeUnit = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0)
const cell = (s: unknown) => String(s).replace(/\|/g, "\\|")

/* ────────────────────────────── 数据面 ────────────────────────────── */

/** 一个块（AST 抽取结果）。 */
export interface BlockRow {
  /** zod schema 变量名（如 `Paragraph`）——只用于定位，type 才是块的稳定标识。 */
  schema: string
  /** 判别字面量（`base("paragraph")` 的参数）——块的稳定 type。 */
  type: string
  /** `base()` 之外的显式字段名（源码声明序）。 */
  fields: string[]
  /** 仓库相对路径（posix）。 */
  site: string
  /** 声明所在 1-based 行号。 */
  line: number
}

/** 三档分组词表（type 数组）。 */
export interface GroupTypes {
  A: string[]
  B: string[]
  C: string[]
}

/** 一次扫描的完整面（渲染与判据的唯一输入）。 */
export interface BlockSurface {
  blocks: BlockRow[]
  groups: GroupTypes
  containers: string[]
  references: string[]
  /** 第一批 type 全集（A 档 9 + B 档 5）。 */
  firstBatch: string[]
  /** 三档词表声明的 type 总数（A+B+C），用于和扫到的块数交叉核对。 */
  declaredCount: number
}

/** 节点在源码里的 1-based 行号（问 SourceFile，不自己数换行）。 */
const lineOf = (sf: ts.SourceFile, node: ts.Node): number => sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1

/**
 * 从一条 `const X = z.strictObject({ ... })` 声明抽块；不是块返回 null。
 * 判块的条件：`z.strictObject` 对象字面量里存在 `...base("字符串字面量")`。
 * 没别的限制——显式字段可以是 shorthand（`rich`）或 `name: expr`（`children: blockChildren`），
 * 都能抽到名字；共用 schema（`Rich`）没有 base 展开，天然不命中。
 * @param stmt - 源码顶层语句。
 * @param sf - 源文件（取行号）。
 * @param site - 仓库相对路径。
 */
function blockOf(stmt: ts.Statement, sf: ts.SourceFile, site: string): BlockRow | null {
  if (!ts.isVariableStatement(stmt)) return null
  for (const decl of stmt.declarationList.declarations) {
    if (!ts.isIdentifier(decl.name) || !decl.initializer) continue
    const init = decl.initializer
    if (!ts.isCallExpression(init) || !ts.isPropertyAccessExpression(init.expression)) continue
    if (init.expression.name.text !== "strictObject") continue
    const recv = init.expression.expression
    if (!ts.isIdentifier(recv) || recv.text !== "z") continue
    const body = init.arguments[0]
    if (!body || !ts.isObjectLiteralExpression(body)) continue

    let type: string | null = null
    const fields: string[] = []
    for (const prop of body.properties) {
      if (ts.isSpreadAssignment(prop)) {
        // `...base("paragraph")`：base 调用的第一个字符串实参就是 type。
        const e = prop.expression
        if (!ts.isCallExpression(e) || !ts.isIdentifier(e.expression) || e.expression.text !== "base") continue
        const arg = e.arguments[0]
        if (arg && ts.isStringLiteral(arg)) type = arg.text
      } else if (ts.isShorthandPropertyAssignment(prop)) {
        fields.push(prop.name.text)
      } else if (ts.isPropertyAssignment(prop) && ts.isIdentifier(prop.name)) {
        fields.push(prop.name.text)
      }
    }
    if (type === null) continue // 没有 base 展开 ⇒ 不是块（Rich 等共用 schema）。
    return { schema: decl.name.text, type, fields, site, line: lineOf(sf, decl) }
  }
  return null
}

/**
 * 扫一段源码里的 28 块 schema（AST 版唯一抽取入口，spec 直接喂构造源码）。
 * @param text - 源码全文。
 * @param site - 仓库相对路径（posix）。
 * @returns 命中的块列表（可能为空）。
 */
export function scanBlockSchemas(text: string, site: string): BlockRow[] {
  const sf = ts.createSourceFile(site, text, ts.ScriptTarget.Latest, true)
  const out: BlockRow[] = []
  for (const stmt of sf.statements) {
    const b = blockOf(stmt, sf, site)
    if (b) out.push(b)
  }
  return out
}

/**
 * 从源码顶层抽一张 `export const X = [...] as const` 字符串数组（词表）。
 * `as const` 包在数组外面（AsExpression），要先剥掉；spread 元素（如 BLOCK_TYPES = [...A,...B,...C]）
 * 不是字符串字面量，直接忽略——本生成器只取四张字面量词表，BLOCK_TYPES 由三档拼接而来。
 * @returns 字符串数组；找不到该导出名返回 null。
 */
function stringArrayOf(sf: ts.SourceFile, name: string): string[] | null {
  for (const stmt of sf.statements) {
    if (!ts.isVariableStatement(stmt)) continue
    for (const decl of stmt.declarationList.declarations) {
      if (!ts.isIdentifier(decl.name) || decl.name.text !== name || !decl.initializer) continue
      let init: ts.Expression = decl.initializer
      if (ts.isAsExpression(init)) init = init.expression
      if (!ts.isArrayLiteralExpression(init)) return null
      const out: string[] = []
      for (const el of init.elements) {
        if (ts.isStringLiteral(el)) out.push(el.text)
      }
      return out
    }
  }
  return null
}

/** 空面（数据源缺席时返回；块数 0 ⇒ 判据判不了，不冒充绿）。 */
const EMPTY_SURFACE: BlockSurface = {
  blocks: [],
  groups: { A: [], B: [], C: [] },
  containers: [],
  references: [],
  firstBatch: [],
  declaredCount: 0,
}

/**
 * 从一段源码组装完整面（纯函数，spec 直接喂构造源码测整条 scan→render 管线）。
 * @param text - 源码全文。
 * @param site - 仓库相对路径。
 */
export function surfaceFromSource(text: string, site = SOURCE_REL): BlockSurface {
  const sf = ts.createSourceFile(site, text, ts.ScriptTarget.Latest, true)
  const groups: GroupTypes = {
    A: stringArrayOf(sf, "A_BASIC_TYPES") ?? [],
    B: stringArrayOf(sf, "B_BUSINESS_TYPES") ?? [],
    C: stringArrayOf(sf, "C_NOTION_TYPES") ?? [],
  }
  const containers = stringArrayOf(sf, "CONTAINER_TYPES") ?? []
  const references = stringArrayOf(sf, "REFERENCE_TYPES") ?? []
  const firstBatch = [...groups.A, ...FIRST_BATCH_B]
  return {
    blocks: scanBlockSchemas(text, site),
    groups,
    containers,
    references,
    firstBatch,
    declaredCount: groups.A.length + groups.B.length + groups.C.length,
  }
}

/**
 * 全仓扫描：读 spec.ts → 抽 28 块 + 五张词表 → 组装面。
 * @param repo - 仓库根。
 * @returns 块面；数据源缺失时返回空面（块数 0 ⇒ 判据判不了，不冒充绿）。
 */
export function scanBlockSurface(repo = REPO): BlockSurface {
  const file = path.join(repo, SOURCE_REL)
  let text: string
  try {
    text = fs.readFileSync(file, "utf8")
  } catch {
    return EMPTY_SURFACE
  }
  return surfaceFromSource(text)
}

/* ────────────────────────────── 渲染 ────────────────────────────── */

/** 宽松渲染面：spec 可喂构造数据（子集字段），与 {@link BlockSurface} 同构。 */
export interface RenderSurface {
  blocks?: BlockRow[]
  groups?: GroupTypes
  containers?: string[]
  references?: string[]
  firstBatch?: string[]
  declaredCount?: number
}

/** 分组的显示名与排序权重。 */
const GROUP_LABEL: Record<string, string> = { A: "A 基础", B: "B 业务", C: "C Notion 扩展", "?": "未分档" }
const GROUP_ORDER: Record<string, number> = { A: 0, B: 1, C: 2, "?": 3 }

/**
 * 渲染 `docs/block-catalog.md` 全文（纯函数：输入 = 扫描面，无 IO、无时间戳 ⇒ 幂等）。
 * @param surface - 扫描结果（spec 可喂构造子集）。
 * @returns 生成物全文（含末尾换行）。
 */
export function renderBlockCatalog(surface?: RenderSurface): string {
  const blocks = surface?.blocks ?? []
  const groups: GroupTypes = surface?.groups ?? { A: [], B: [], C: [] }
  const containers = new Set(surface?.containers ?? [])
  const references = new Set(surface?.references ?? [])
  const firstBatch = new Set(surface?.firstBatch ?? [])
  const declaredCount = surface?.declaredCount ?? groups.A.length + groups.B.length + groups.C.length

  const groupOf = (t: string): string =>
    groups.A.includes(t) ? "A" : groups.B.includes(t) ? "B" : groups.C.includes(t) ? "C" : "?"
  const sorted = [...blocks].sort((a, b) => GROUP_ORDER[groupOf(a.type)]! - GROUP_ORDER[groupOf(b.type)]! || byCodeUnit(a.type, b.type))
  const countOf = (g: string) => sorted.filter((b) => groupOf(b.type) === g).length

  const lines: string[] = []
  lines.push(HEADER, "")
  lines.push("# block catalog（生成物，勿手改）", "")
  lines.push(
    `共 ${sorted.length} 种块 · A 基础 ${countOf("A")} / B 业务 ${countOf("B")} / C Notion ${countOf("C")}` +
      `${countOf("?") ? ` / 未分档 ${countOf("?")}` : ""} · 容器 ${sorted.filter((b) => containers.has(b.type)).length} · ` +
      `引用 ${sorted.filter((b) => references.has(b.type)).length} · 第一批 ${sorted.filter((b) => firstBatch.has(b.type)).length} · ` +
      `词表声明 ${declaredCount}。` +
      `重生成：\`node scripts/gen-block-catalog.ts\`；新鲜度：\`node scripts/gates/verify-block-catalog.ts --check\`。`,
    "",
  )
  lines.push(
    "本表由 `@matter/blocks/src/spec.ts` 的 zod schema AST 抽取得出（不读正则）：每个块是 " +
      "`const X = z.strictObject({ ...base(\"type\"), <显式字段...> })`，`type` 取自 `base(\"…\")` 的参数，" +
      "「字段」列 `base()` 之外的显式属性（所有块共有的 `id` + `type` 来自 `base()`，不重复列）。" +
      "分组取自 `A_BASIC_TYPES` / `B_BUSINESS_TYPES` / `C_NOTION_TYPES` 三张词表，" +
      "「容器」「引用」标记取自 `CONTAINER_TYPES` / `REFERENCE_TYPES`——词表是分组的唯一真相源，改词表不改 schema（或反之）都会让本表变、判据红。",
    "",
  )
  lines.push(
    "「第一批」14 种 = A 档 9（全量）+ B 档 5（issueRef / docRef / mermaid / toggle / view），" +
      "口径由 ISS-532 钉死；callout / table 留 P6，加第 15 种另立单。" +
      "块按 A→B→C 分组、组内按 type 码位序排列；重生成幂等（无时间戳）。",
    "",
  )
  if (!sorted.length) {
    lines.push("（无：扫描面里没有任何 `z.strictObject({ ...base(\"…\"), ... })` 块 schema）", "")
    return lines.join("\n")
  }
  for (const g of ["A", "B", "C", "?"]) {
    const section = sorted.filter((b) => groupOf(b.type) === g)
    if (!section.length) continue
    lines.push(`## ${GROUP_LABEL[g]}（${section.length} 种）`, "")
    lines.push("| type | 字段 | 容器 | 引用 | 批次 | 第一批 |", "|---|---|---|---|---|---|")
    for (const b of section) {
      const fields = b.fields.length ? b.fields.map((f) => `\`${cell(f)}\``).join("、") : "—"
      lines.push(
        `| \`${cell(b.type)}\` | ${fields} | ${containers.has(b.type) ? "是" : "否"} | ` +
          `${references.has(b.type) ? "是" : "否"} | ${GROUP_LABEL[g]} | ${firstBatch.has(b.type) ? "✓" : "—"} |`,
      )
    }
    lines.push("")
  }
  return lines.join("\n")
}

/** 一次扫描 + 渲染（判据与 CLI 走同一条路，不许各写一份）。 */
export function buildBlockCatalog(repo = REPO): string {
  return renderBlockCatalog(scanBlockSurface(repo))
}

function main(argv: string[]): number {
  const check = argv.includes("--check")
  const target = path.join(REPO, OUT_REL)
  const text = buildBlockCatalog(REPO)
  if (check) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null
    if (current === text) {
      console.log(`✓ ${OUT_REL} 与源码一致`)
      return 0
    }
    console.error(`✗ ${OUT_REL} ${current === null ? "不存在" : "是旧的"} —— 跑生成器 \`node scripts/gen-block-catalog.ts\` 再提交`)
    return 1
  }
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, text)
  console.log(`✓ 已写 ${OUT_REL}（${text.length} B）`)
  return 0
}

const invokedDirectly = (() => {
  const argv1 = process.argv[1]
  if (!argv1) return false
  try {
    return pathToFileURL(path.resolve(argv1)).href === import.meta.url
  } catch {
    return false
  }
})()

if (invokedDirectly) process.exitCode = main(process.argv.slice(2))

#!/usr/bin/env node
/**
 * gen-field-catalog —— 三域字段清单生成器（ISS-896 / P3-F1，DOC-516 §四 D8，照 D0 形态新建）。
 *
 * 一份 schema = 类型 + 校验 + UI 组件 + 可写性 + 可索引（DOC-512 §5.6.3）—— 前四样活在
 * zod schema 里，本表把第五样之后的元数据面（`.meta({ writable, widget, indexable })`）摊开成
 * 可读的字段目录，消除「字段清单只能读源码获得」这一环。
 *
 * 机制与 D0/D1 同构，**失败驱动**：改 schema → 忘跑生成器 → `verify-field-catalog --check` 红 →
 * `node scripts/gen-field-catalog.ts` → 提交。生成物进 git、不手改、重生成幂等（无时间戳）。
 *
 * 读 AST 不读正则（照 D0/D1 先例）：注释 / 字符串里的 `z.strictObject` 不是 AST 节点，天然抽不到。
 *
 * **字段清单 schema 的判别口径**（三条全满足才收，缺一不收）：
 *   ① `export const X = z.strictObject({ ...字面量... })` —— 衍生 schema（`.omit().partial()`、
 *      `.extend()`）没有字面量属性，天然不命中；
 *   ② 每个属性值是 `z.*` 起头的调用链 —— 引用型属性（`DocRecord` 的 `props: DocProps`）
 *      与 spread（blocks 叶子的 `...base(...)`）天然不命中；
 *   ③ 每条链带 `.meta({ writable, widget, indexable })` 且三键俱全 —— `@matter/blocks` 的
 *      28 个 block 叶子（无 `.meta()`）天然不命中。
 * 由此「加字段忘写 meta」⇒ schema 整张从表里消失 ⇒ 生成物变 ⇒ 判据红 —— meta 纪律由机器兜底。
 *
 * 为什么是独立生成器而不是 D1 框架的第四个 extractor：`scripts/gen-catalog.spec.ts` 把
 * `EXTRACTORS` 钉死为「三个真实消费者」，该文件不在本单写范围（详见 ISS-896 施工图 ## 范围）。
 * 生成器按同源纯函数组织（scan → surface → render），将来迁入框架是顺手事。
 *
 * 用法：node scripts/gen-field-catalog.ts            # 重生成
 *       node scripts/gen-field-catalog.ts --check    # 只比对，旧了退出 1（与判据同口径）
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import ts from "typescript"

/** 仓库根（本文件在 `<repo>/scripts/`）。 */
export const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")

export const OUT_REL = "docs/field-catalog.md"
/** 文件头逐字稳定，判据此校验（形态对齐 D0）。 */
export const HEADER = "<!-- Generated by scripts/gen-field-catalog.ts — do not edit by hand. -->"

/** 扫描时跳过的目录名（口径同 D0 gen-ctx-catalog）。`lib` 是产物，`tests` 不是契约面。 */
const SKIP_DIRS = new Set(["node_modules", "dist", "lib", "tests", "test", ".git", "coverage"])
const posix = (p: string) => p.split(path.sep).join("/")
const byCodeUnit = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0)
const cell = (s: unknown) => String(s).replace(/\|/g, "\\|")

/* ────────────────────────────── 数据面 ────────────────────────────── */

/** 一条 `.meta()` 元数据（判别口径保证三键俱全；null 只是类型兜底，不会出现在收进来的行上）。 */
export interface FieldMeta {
  writable: string | null
  widget: string | null
  indexable: boolean | null
}

/** 一个字段（AST 抽取结果）。 */
export interface FieldRow {
  name: string
  /** zod 构造形态，如 `z.string` / `z.array<z.string>`；后缀来源见 {@link optional} / {@link nullable}。 */
  shape: string
  /** 链上有 `.optional()`（值可缺）。渲染为 `?` 后缀。 */
  optional: boolean
  /** 链上有 `.nullable()` / `.nullish()`（值可为 null）。渲染为 `|null` 后缀（nullish 两者皆真）。 */
  nullable: boolean
  meta: FieldMeta
  site: string
  line: number
}

/** 一张字段清单 schema（如 `IssueProps`）。 */
export interface FieldSchema {
  /** schema 导出名。 */
  name: string
  /** 来源包名（`@matter/issue` 形态）。 */
  pkg: string
  site: string
  line: number
  fields: FieldRow[]
}

export interface FieldSurface {
  schemas: FieldSchema[]
  /** 扫到的包总数（判据的语料存在性口径）。 */
  packageCount: number
}

/** 节点在源码里的 1-based 行号（问 SourceFile，不自己数换行）。 */
const lineOf = (sf: ts.SourceFile, node: ts.Node): number => sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1

/**
 * 从一条调用链抽 zod 构造形态（如 `z.string` / `z.iso.date` / `z.array<z.string>`）。
 * 校验器（`.min` / `.regex` / `.int` …）不是形态，不进结果；`.optional` / `.meta` 由调用方单独收。
 * @param node - 链的最内层表达式（剥掉 `.meta` / `.optional` / 校验器之后剩下的 `z.*` 构造调用）。
 * @returns 形态文本；不是 `z.*` 构造（标识符引用、字面量等）返回 null。
 */
function zodShapeOf(node: ts.Expression): string | null {
  if (!ts.isCallExpression(node)) return null
  const callee = node.expression
  if (!ts.isPropertyAccessExpression(callee)) return null
  // 属性链文本：`z.string` 的 callee 就是 (z).string；`z.iso.date` 是 ((z).iso).date。
  const segments: string[] = []
  let cur: ts.Expression = callee
  while (ts.isPropertyAccessExpression(cur)) {
    segments.unshift(cur.name.text)
    cur = cur.expression
  }
  if (!ts.isIdentifier(cur) || cur.text !== "z" || !segments.length) return null
  const head = `z.${segments.join(".")}`
  if (segments[0] === "array") {
    // 元素形态进尖括号：`z.array(z.string())` → `z.array<z.string>`（元素不是 z.* 构造则只写 `z.array`）。
    const el = node.arguments[0]
    if (el) {
      const inner = zodShapeOf(el)
      if (inner) return `${head}<${inner}>`
    }
  }
  return head
}

/** 表达式是否 `z` 命名空间根的属性链（`z` / `z.iso` / `z.iso.date` 的 receiver 形态）。 */
function isZRoot(e: ts.Expression): boolean {
  let cur: ts.Expression = e
  while (ts.isPropertyAccessExpression(cur)) cur = cur.expression
  return ts.isIdentifier(cur) && cur.text === "z"
}

/**
 * 抽一条字段链：`z.string().regex(X).optional().nullable().meta({ … })`。
 * 从最外层逐层向内剥：`.meta` 抽三键（抽不全 ⇒ 不算字段链）；`.optional` / `.nullable` / `.nullish`
 * 记可空性（渲染为后缀，**不许静默吞**——吞了重生成判据照绿，可空性无出声路径，ISS-896 审查 minor）；
 * 其余是校验器跳过；receiver 落到 `z` 根 ⇒ 当前节点是构造器调用，交给 {@link zodShapeOf}。
 * 只认 `.meta(...)` 的内联对象字面量（引用型参数抽不到键，按口径不算字段链——将来真出现时
 * schema 整张不收、判据红灯出声，不静默）。
 * @param node - 属性初始化表达式。
 * @returns 链的四件（zod 形态 / optional / nullable / meta 三键）；不满足字段链口径返回 null。
 */
function fieldChainOf(node: ts.Expression): { shape: string; optional: boolean; nullable: boolean; meta: FieldMeta } | null {
  let cur: ts.Expression = node
  let optional = false
  let nullable = false
  let meta: FieldMeta | null = null
  while (ts.isCallExpression(cur) && ts.isPropertyAccessExpression(cur.expression)) {
    const method = cur.expression.name.text
    const receiver = cur.expression.expression
    // receiver 是 `z` 根 ⇒ cur 已是构造器调用（`z.string()` / `z.iso.date()` …），到此为止。
    if (isZRoot(receiver)) break
    if (method === "meta") {
      const arg = cur.arguments[0]
      if (!arg || !ts.isObjectLiteralExpression(arg)) return null
      const m: FieldMeta = { writable: null, widget: null, indexable: null }
      for (const p of arg.properties) {
        if (!ts.isPropertyAssignment(p) || !ts.isIdentifier(p.name)) continue
        const key = p.name.text
        if (key === "writable" && ts.isStringLiteral(p.initializer)) m.writable = p.initializer.text
        else if (key === "widget" && ts.isStringLiteral(p.initializer)) m.widget = p.initializer.text
        else if (key === "indexable" && (p.initializer.kind === ts.SyntaxKind.TrueKeyword || p.initializer.kind === ts.SyntaxKind.FalseKeyword)) {
          m.indexable = p.initializer.kind === ts.SyntaxKind.TrueKeyword
        }
      }
      // 三键俱全才算（判别口径 ③）：缺键 = schema 违规，宁可让生成物变化出红，不留静默空格。
      if (m.writable === null || m.widget === null || m.indexable === null) return null
      meta = m
    } else if (method === "optional") {
      optional = true
    } else if (method === "nullable") {
      nullable = true
    } else if (method === "nullish") {
      // zod 语义：nullish = optional ∪ nullable，两者皆真。
      optional = true
      nullable = true
    } // 其余（.min/.regex/.int/.max/…）是校验器，不是形态，跳过。
    cur = receiver
  }
  const shape = zodShapeOf(cur)
  if (shape === null || meta === null) return null
  return { shape, optional, nullable, meta }
}

/**
 * 扫一个 TS 源文件里的字段清单 schema（AST 版唯一抽取入口，spec 直接喂构造源码）。
 * 口径三条（z.strictObject 字面量 / 属性全为 z.* 链 / 链全带三键 meta）见文件头注；
 * 注释与字符串不是 AST 节点，天然抽不到。
 * @param text - 源码全文。
 * @param site - 仓库相对路径（posix）。
 * @returns 命中的 schema 列表（可能为空）。
 */
export function scanFieldSchemas(text: string, site: string): FieldSchema[] {
  const sf = ts.createSourceFile(site, text, ts.ScriptTarget.Latest, true)
  const out: FieldSchema[] = []
  for (const stmt of sf.statements) {
    if (!ts.isVariableStatement(stmt)) continue
    const isExport = stmt.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword) === true
    if (!isExport) continue
    for (const decl of stmt.declarationList.declarations) {
      if (!ts.isIdentifier(decl.name) || !decl.initializer) continue
      const init = decl.initializer
      if (!ts.isCallExpression(init) || !ts.isPropertyAccessExpression(init.expression)) continue
      const zCall = init.expression.expression
      if (!ts.isIdentifier(zCall) || zCall.text !== "z" || init.expression.name.text !== "strictObject") continue
      const body = init.arguments[0]
      if (!body || !ts.isObjectLiteralExpression(body) || !body.properties.length) continue
      // 口径 ②③：**每个**属性都得是带三键 meta 的 z.* 链；一个不满足 ⇒ 整张不是字段清单。
      const fields: FieldRow[] = []
      let allFields = true
      for (const p of body.properties) {
        if (!ts.isPropertyAssignment(p) || !ts.isIdentifier(p.name)) {
          allFields = false
          break
        }
        const chain = fieldChainOf(p.initializer)
        if (!chain) {
          allFields = false
          break
        }
        fields.push({
          name: p.name.text,
          shape: chain.shape,
          optional: chain.optional,
          nullable: chain.nullable,
          meta: chain.meta,
          site,
          line: lineOf(sf, p),
        })
      }
      if (!allFields) continue
      out.push({ name: decl.name.text, pkg: "", site, line: lineOf(sf, decl), fields })
    }
  }
  return out
}

/**
 * 全仓扫描：列包（`packages/<group>/<pkg>`）→ 逐包 `src/**`（跳过产物与 spec）→ 逐文件抽 schema。
 * @param repo - 仓库根。
 * @returns 字段清单面（schema 按包名码位序、schema 名码位序；字段保持源码声明序）。
 */
export function scanFieldSurface(repo = REPO): FieldSurface {
  const out: FieldSchema[] = []
  let packageCount = 0
  const packagesRoot = path.join(repo, "packages")
  let groups: fs.Dirent[]
  try {
    groups = fs.readdirSync(packagesRoot, { withFileTypes: true })
  } catch {
    return { schemas: [], packageCount: 0 }
  }
  for (const g of groups.sort((a, b) => byCodeUnit(a.name, b.name))) {
    if (!g.isDirectory() || SKIP_DIRS.has(g.name)) continue
    let pkgs: fs.Dirent[]
    try {
      pkgs = fs.readdirSync(path.join(packagesRoot, g.name), { withFileTypes: true })
    } catch {
      continue
    }
    for (const p of pkgs.sort((a, b) => byCodeUnit(a.name, b.name))) {
      if (!p.isDirectory() || SKIP_DIRS.has(p.name)) continue
      const pkgDir = path.join(packagesRoot, g.name, p.name)
      let pkgName = ""
      try {
        pkgName = String(JSON.parse(fs.readFileSync(path.join(pkgDir, "package.json"), "utf8")).name ?? "")
      } catch {
        continue // 没有合法 package.json 的目录不是包（口径同 D0）。
      }
      packageCount++
      const srcFiles: string[] = []
      const walk = (dir: string): void => {
        let entries: fs.Dirent[]
        try {
          entries = fs.readdirSync(dir, { withFileTypes: true })
        } catch {
          return
        }
        for (const e of entries) {
          if (e.isDirectory()) {
            if (SKIP_DIRS.has(e.name)) continue
            walk(path.join(dir, e.name))
          } else if (e.name.endsWith(".ts") && !e.name.endsWith(".d.ts") && !e.name.endsWith(".spec.ts")) {
            srcFiles.push(path.join(dir, e.name))
          }
        }
      }
      walk(path.join(pkgDir, "src"))
      for (const f of srcFiles.sort(byCodeUnit)) {
        const site = posix(path.relative(repo, f))
        for (const schema of scanFieldSchemas(fs.readFileSync(f, "utf8"), site)) {
          out.push({ ...schema, pkg: pkgName })
        }
      }
    }
  }
  out.sort((a, b) => byCodeUnit(a.pkg, b.pkg) || byCodeUnit(a.name, b.name))
  return { schemas: out, packageCount }
}

/* ────────────────────────────── 渲染 ────────────────────────────── */

/** 宽松渲染面：spec 可喂构造数据（子集字段），与 {@link FieldSurface} 同构。 */
export interface RenderSurface {
  schemas?: FieldSchema[]
  packageCount?: number
}

/** 类型列后缀：`?` 表 optional（值可缺）、`|null` 表 nullable（值可为 null）；nullish 两者叠加。 */
const shapeCell = (f: Pick<FieldRow, "shape" | "optional" | "nullable">): string =>
  `${f.shape}${f.optional ? "?" : ""}${f.nullable ? "|null" : ""}`
const metaCell = (v: string | boolean | null): string => (v === null ? "—" : v === true ? "是" : v === false ? "否" : String(v))

/**
 * 渲染 `docs/field-catalog.md` 全文（纯函数：输入 = 扫描面，无 IO、无时间戳 ⇒ 幂等）。
 * @param surface - 扫描结果（spec 可喂构造子集）。
 * @returns 生成物全文（含末尾换行）。
 */
export function renderFieldCatalog(surface?: RenderSurface): string {
  const schemas = surface?.schemas ?? []
  const packageCount = surface?.packageCount ?? 0
  const fieldCount = schemas.reduce((n, s) => n + s.fields.length, 0)
  const lines: string[] = []
  lines.push(HEADER, "")
  lines.push("# field catalog（生成物，勿手改）", "")
  lines.push(
    `字段清单 schema ${schemas.length} 张 · 字段 ${fieldCount} 条 · 覆盖包 ${schemas.length ? new Set(schemas.map((s) => s.pkg)).size : 0} 个 · 扫描面 ${packageCount} 包。` +
      "重生成：`node scripts/gen-field-catalog.ts`；新鲜度：`node scripts/gates/verify-field-catalog.ts --check`。",
    "",
  )
  lines.push(
    "本表由三域 zod schema 的 AST 抽取得出（不读正则）：`export const X = z.strictObject({ …字面量… })` 且**每个**" +
      "属性值是 `z.*` 起头的调用链、链上带 `.meta({ writable, widget, indexable })` 三键俱全，才算一张字段清单。" +
      "由此衍生 schema（`.omit().partial()`，无字面量属性）、引用型包装（`DocRecord` 的 `props: DocProps`）与" +
      "`@matter/blocks` 的 block 叶子（无 `.meta()`）天然不在表里 —— 它们不是域字段清单。",
    "",
  )
  lines.push(
    "「类型」列写 **zod 构造形态**：校验器（`.min` / `.regex` / `.int` …）不是形态，不进此列；" +
      "可空性记为后缀——`.optional()`（值可缺）为 `?`、`.nullable()`（值可为 null）为 `|null`、`.nullish()` 为 `?|null`；" +
      "`meta` 的额外键（如 `branded`）不进五列。" +
      "字段按源码声明序排列（schema 内的分档注释因此可读），schema 按包名码位序分节。重生成幂等。",
    "",
  )
  if (!schemas.length) {
    lines.push("（无：扫描面里没有任何 `z.strictObject` 字段清单 schema）", "")
    return lines.join("\n")
  }
  for (const s of schemas) {
    lines.push(`## ${s.pkg} · ${s.name}（${s.fields.length} 字段）`, "")
    lines.push(`声明：\`${cell(s.site)}:${s.line}\``, "")
    lines.push("| 字段 | 类型 | writable | widget | indexable |")
    lines.push("|---|---|---|---|---|")
    for (const f of s.fields) {
      lines.push(
        `| \`${cell(f.name)}\` | \`${cell(shapeCell(f))}\` | ${cell(metaCell(f.meta.writable))} | ${cell(metaCell(f.meta.widget))} | ${metaCell(f.meta.indexable)} |`,
      )
    }
    lines.push("")
  }
  return lines.join("\n")
}

/** 一次扫描 + 渲染（判据与 CLI 走同一条路，不许各写一份）。 */
export function buildFieldCatalog(repo = REPO): string {
  return renderFieldCatalog(scanFieldSurface(repo))
}

function main(argv: string[]): number {
  const check = argv.includes("--check")
  const target = path.join(REPO, OUT_REL)
  const text = buildFieldCatalog(REPO)
  if (check) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null
    if (current === text) {
      console.log(`✓ ${OUT_REL} 与源码一致`)
      return 0
    }
    console.error(`✗ ${OUT_REL} ${current === null ? "不存在" : "是旧的"} —— 跑生成器 \`node scripts/gen-field-catalog.ts\` 再提交`)
    return 1
  }
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, text)
  console.log(`✓ 已写 ${OUT_REL}（${text.length} B）`)
  return 0
}

const invokedDirectly = (() => {
  const argv1 = process.argv[1]
  if (!argv1) return false
  try {
    return pathToFileURL(path.resolve(argv1)).href === import.meta.url
  } catch {
    return false
  }
})()

if (invokedDirectly) process.exitCode = main(process.argv.slice(2))

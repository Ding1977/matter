#!/usr/bin/env node
/**
 * gen-ctx-catalog —— 从源码的 **TypeScript AST** 扫出 ctx 面，生成 `docs/ctx-catalog.md`（ISS-862 建，ISS-892 改 AST）。
 *
 * 为什么从文本启发式改成 AST（ISS-892 / 轨 D D0）：旧版 `gen-ctx-catalog.mjs` 用注释掩码 + 正则，
 * 对「注释里的 `ctx.provide`」「字符串里的声明」「跨行/多修饰符的成员」只能靠掩码近似，容易漏报或误报。
 * 掩码本身也是一份手写的词法分析器 —— 与 TS 编译器对源码的理解分叉时，错的是静默的（表里少一行、
 * 判据仍绿）。这里改用 `ts.createSourceFile` + `ts.forEachChild`：注释不是节点、字符串不是声明，
 * 天然不会被抽出来；行号直接问 SourceFile，不再自己数换行。
 *
 * 机制**不是「自动同步」，是失败驱动**：
 *   改源码 → 忘跑生成器 → `scripts/gates/verify-ctx-catalog.ts --check` 红 → 跑本脚本 → 提交。
 * 所以生成物必须**进 git**，否则「红」这件事没人看得见。
 *
 * 扫描面：`packages/<group>/<pkg>/package.json` + 各包 `src` 下的 `.ts` 文件。
 * ⛔ `lib/` 是构建产物（`lib/types/index.d.ts` 里也有一份 `declare module`），必须排除，
 *    否则同一件事在表里出现两次。
 *
 * ⛔ **不许按包名字面匹配源码**：`@matter/storage` 是 `@matter/storage-journal` 的**前缀**
 *    （ISS-515 踩过同类）。这里一律结构化：模块名取 `ModuleDeclaration.name.text` 整串相等，
 *    成员名只从声明体里取，不做任何「包含这个包名就算」的判断。
 *
 * 幂等：不写时间戳，一切按码位序排序 ⇒ 连跑两次字节相同。
 *
 * 用法：node scripts/gen-ctx-catalog.ts           # 写 docs/ctx-catalog.md
 *       node scripts/gen-ctx-catalog.ts --check   # 只比对：旧了退出 1（与判据同口径）
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import ts from "typescript"
import type { Extractor } from "./gen-catalog.ts"

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
/** 生成物路径（相对仓库根）。判据与人类文档都指向这一处。 */
export const OUT_REL = "docs/ctx-catalog.md"
/** 文件头必须逐字一致（DOC-512 §5.6.1 对齐 DSH `config-catalog.md` 的形态）。 */
export const HEADER = "<!-- Generated by scripts/gen-ctx-catalog.ts — do not edit by hand. -->"

/** 扫描时跳过的目录名。`lib` 是产物，`tests` 不是契约面。 */
const SKIP_DIRS = new Set(["node_modules", "dist", "lib", "tests", "test", ".git", "coverage"])

const ctlgPosix = (p: string) => p.split(path.sep).join("/")
const ctlgByCodeUnit = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0)

/** 一个 ctx 键（AST 抽取结果）。导出给 spec 喂构造语料。 */
export interface CtxKey {
  key: string
  form: string
  site: string
  line: number
}
/** 一个类型化事件（AST 抽取结果）。 */
export interface CtxEvent {
  name: string
  site: string
  line: number
  mode: string
}
/** 单文件 AST 扫描产物。4 类声明各对应一个字段，`hasApply` 供类角色列用。 */
export interface SourceScan {
  keys: CtxKey[]
  events: CtxEvent[]
  serviceClasses: string[]
  hasApply: boolean
}

/** 节点在源码里的 1-based 行号（问 SourceFile，不自己数换行）。 */
const lineOf = (sf: ts.SourceFile, node: ts.Node): number => sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1

/** 属性/方法名：标识符与字符串字面量都收（声明合并两侧都可能是带引号的名）。 */
function nameText(name: ts.PropertyName | ts.BindingName | undefined): string | null {
  if (!name) return null
  if (ts.isIdentifier(name) || ts.isStringLiteral(name) || ts.isNoSubstitutionTemplateLiteral(name)) return name.text
  return null
}

/** 事件 JSDoc 上的 `@mode`（如 `@mode emit`）—— 从 AST 挂载的 JSDoc 读，不回溯文本。 */
function jsdocMode(node: ts.Node): string {
  for (const tag of ts.getJSDocTags(node)) {
    if (tag.tagName.text === "mode" && typeof tag.comment === "string") return tag.comment.trim()
  }
  return ""
}

/**
 * 扫一个 TS 源文件的 4 类声明。这是 AST 版的唯一抽取入口，spec 直接喂构造源码。
 *
 * ① `declare module "<整串>"` 里的 `interface Context` / `StorageForms` / `Events`
 * ② `class X extends Service` + 类体内的 `super(ctx, "<key>")`
 * ③ `ctx.provide("<key>", …)` / `ctx.provide(storageBackendServiceKey("<name>"), …)`
 * （④ `Events` 与 ① 同处遍历，单列只为对齐规格的四类）
 *
 * 注释与字符串不是 AST 节点，天然不会被抽出来 —— 这是改 AST 的收益，不需要额外掩码。
 * @param text - 源码全文。
 * @param site - 仓库相对路径，写进结果的「声明位置」列。
 */
export function scanSource(text: string, site: string): SourceScan {
  const sf = ts.createSourceFile(site, text, ts.ScriptTarget.Latest, true)
  const keys: CtxKey[] = []
  const events: CtxEvent[] = []
  const serviceClasses: string[] = []

  // ① declare module（ctx 键类型扩展）+ Events
  for (const stmt of sf.statements) {
    if (!ts.isModuleDeclaration(stmt) || !ts.isStringLiteral(stmt.name)) continue
    const mod = stmt.name.text
    if (mod !== "@deepseek-ai/cordis" && mod !== "@matter/storage") continue
    const body = stmt.body
    if (!body || !ts.isModuleBlock(body)) continue
    for (const inner of body.statements) {
      if (!ts.isInterfaceDeclaration(inner)) continue
      const iface = inner.name.text
      if (mod === "@deepseek-ai/cordis" && iface === "Context") {
        for (const m of inner.members) {
          if (!ts.isPropertySignature(m)) continue
          const name = nameText(m.name)
          if (name === null) continue
          keys.push({ key: name, form: "服务键（`declare module` 合并 `Context`）", site, line: lineOf(sf, m) })
        }
      } else if (mod === "@deepseek-ai/cordis" && iface === "Events") {
        for (const m of inner.members) {
          if (!ts.isMethodSignature(m)) continue
          const name = nameText(m.name)
          if (name === null) continue
          events.push({ name, mode: jsdocMode(m), site, line: lineOf(sf, m) })
        }
      } else if (mod === "@matter/storage" && iface === "StorageForms") {
        for (const m of inner.members) {
          if (!ts.isPropertySignature(m)) continue
          const name = nameText(m.name)
          if (name === null) continue
          keys.push({ key: `storage.${name}`, form: "hub 表单键（`StorageForms` 合并，经 `ctx.storage.<form>` 读）", site, line: lineOf(sf, m) })
        }
      }
    }
  }

  // ② extends Service + super(ctx, "<key>")
  for (const stmt of sf.statements) {
    if (!ts.isClassDeclaration(stmt) || !stmt.name) continue
    const clsName = stmt.name.text
    const extendsService = stmt.heritageClauses?.some(
      (h) => h.token === ts.SyntaxKind.ExtendsKeyword &&
        h.types.some((t) => ts.isExpressionWithTypeArguments(t) && ts.isIdentifier(t.expression) && t.expression.text === "Service"),
    )
    if (!extendsService) continue
    serviceClasses.push(clsName)
    let found = false
    const findSuper = (n: ts.Node): void => {
      if (found) return
      if (ts.isCallExpression(n) && n.expression.kind === ts.SyntaxKind.SuperKeyword && n.arguments.length >= 2) {
        const keyArg = n.arguments[1]
        if (keyArg && ts.isStringLiteral(keyArg)) {
          keys.push({ key: keyArg.text, form: `Service 子类（\`class ${clsName}\` 的 \`super(ctx, …)\`）`, site, line: lineOf(sf, n) })
          found = true
          return
        }
      }
      ts.forEachChild(n, findSuper)
    }
    ts.forEachChild(stmt, findSuper)
  }

  // ③ ctx.provide（动态注册）—— 遍历整棵树，嵌套函数内的调用也算（与旧版口径一致）。
  const findProvide = (n: ts.Node): void => {
    if (
      ts.isCallExpression(n) && ts.isPropertyAccessExpression(n.expression) &&
      ts.isIdentifier(n.expression.expression) && n.expression.expression.text === "ctx" &&
      n.expression.name.text === "provide"
    ) {
      const arg = n.arguments[0]
      if (arg && ts.isStringLiteral(arg)) {
        keys.push({ key: arg.text, form: "动态注册（`ctx.provide(…)`）", site, line: lineOf(sf, n) })
      } else if (arg && ts.isCallExpression(arg) && ts.isIdentifier(arg.expression) && arg.expression.text === "storageBackendServiceKey") {
        const nameArg = arg.arguments[0]
        if (nameArg && ts.isStringLiteral(nameArg)) {
          keys.push({ key: `storage.backend.${nameArg.text}`, form: "动态注册（`ctx.provide(…)`）", site, line: lineOf(sf, n) })
        }
      }
    }
    ts.forEachChild(n, findProvide)
  }
  ts.forEachChild(sf, findProvide)

  // 类角色列用：只在**顶层** `export function apply` 算插件（与旧版正则口径一致）。
  const hasApply = sf.statements.some(
    (s) => ts.isFunctionDeclaration(s) && s.name?.text === "apply" &&
      s.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword),
  )

  return { keys, events, serviceClasses, hasApply }
}

/**
 * 扫一个包：包名、源码文件、ctx 声明。
 * @param repo - 仓库根。
 * @param pkgDir - `packages/<group>/<pkg>` 绝对路径。
 */
function ctlgScanPackage(repo: string, pkgDir: string) {
  const pkgJsonPath = path.join(pkgDir, "package.json")
  let pkg: { name?: unknown; description?: unknown }
  try {
    pkg = JSON.parse(fs.readFileSync(pkgJsonPath, "utf8"))
  } catch {
    return null
  }
  const rel = (p: string) => ctlgPosix(path.relative(repo, p))
  const srcDir = path.join(pkgDir, "src")
  const files: string[] = []
  const ctlgWalkSrc = (dir: string): void => {
    let entries: fs.Dirent[]
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true })
    } catch {
      return
    }
    for (const e of entries) {
      if (e.isDirectory()) {
        if (SKIP_DIRS.has(e.name)) continue
        ctlgWalkSrc(path.join(dir, e.name))
      } else if (e.name.endsWith(".ts") && !e.name.endsWith(".d.ts") && !e.name.endsWith(".spec.ts")) {
        files.push(path.join(dir, e.name))
      }
    }
  }
  ctlgWalkSrc(srcDir)
  files.sort(ctlgByCodeUnit)

  const keys: CtxKey[] = []
  const events: CtxEvent[] = []
  const serviceClasses: string[] = []
  let hasApply = false

  for (const file of files) {
    const src = fs.readFileSync(file, "utf8")
    const site = rel(file)
    const scanned = scanSource(src, site)
    keys.push(...scanned.keys)
    events.push(...scanned.events)
    serviceClasses.push(...scanned.serviceClasses)
    hasApply ||= scanned.hasApply
  }

  return {
    name: String(pkg.name ?? ""),
    dir: rel(pkgDir),
    description: String(pkg.description ?? ""),
    serviceClasses,
    hasApply,
    keys,
    events,
  }
}

/**
 * 扫全仓的 ctx 面。**这是唯一的入口** —— 将来加表（blocks / tools / fields）在这里挂。
 *
 * 现有三张表：`packages`（包清单）、`keys`（ctx 键对照）、`events`（事件清单）。
 * 加表的口径：新增一个 `scan*()` + 在 {@link renderCatalog} 里加一段，不改动已有表。
 * ⛔ 别把 extractor 拆成 `extractors/` 目录 —— 现在只有三张表、一个消费者，
 *    目录化只是把同一段逻辑挪个位置（AGENTS.md 简洁原则）。
 * @param repo - 仓库根。
 */
export function scanCtxSurface(repo = REPO) {
  const root = path.join(repo, "packages")
  const packages: ReturnType<typeof ctlgScanPackage>[] = []
  let groups: fs.Dirent[]
  try {
    groups = fs.readdirSync(root, { withFileTypes: true })
  } catch {
    return { packages: [], keyRows: [], eventRows: [] }
  }
  for (const g of groups.sort((a, b) => ctlgByCodeUnit(a.name, b.name))) {
    if (!g.isDirectory() || SKIP_DIRS.has(g.name)) continue
    let pkgs: fs.Dirent[]
    try {
      pkgs = fs.readdirSync(path.join(root, g.name), { withFileTypes: true })
    } catch {
      continue
    }
    for (const p of pkgs.sort((a, b) => ctlgByCodeUnit(a.name, b.name))) {
      if (!p.isDirectory()) continue
      const scanned = ctlgScanPackage(repo, path.join(root, g.name, p.name))
      if (scanned) packages.push(scanned)
    }
  }
  packages.sort((a, b) => ctlgByCodeUnit(a.name ?? "", b.name ?? ""))

  // 包内与跨包都按 key 去重（同一个键可能既被 `declare module` 声明、又被 `ctx.provide` 运行时补注）。
  const keyRows: (CtxKey & { pkg: string })[] = []
  for (const pkg of packages) {
    if (!pkg) continue
    const seen = new Map<string, CtxKey & { pkg: string }>()
    for (const k of pkg.keys) {
      const prev = seen.get(k.key)
      if (prev) {
        if (!prev.form.includes(k.form)) prev.form = `${prev.form} + ${k.form}`
        continue
      }
      const row = { ...k, pkg: String(pkg.name) }
      seen.set(k.key, row)
      keyRows.push(row)
    }
  }
  const eventRows = packages.flatMap((pkg) => (pkg?.events ?? []).map((e) => ({ ...e, pkg: String(pkg?.name) })))

  return { packages, keyRows, eventRows }
}

/**
 * ctx 键的单复数判据（**形状判据，不是语义判据**）。
 *
 * DOC-512 §4.1.1 要求「类角色与 key 单复数必须一致」，但**角色定名要人判**
 * （Store / Registry / Directory / …）。本函数只判形状，且把规则写进生成物，读者可复核：
 *   · hub 表单键（`StorageForms` 合并出来的）⇒ 标「表单」，它不是一个独立服务键
 *   · 其余（服务键 / 动态注册键）按**最后一段**判：以 `s` 结尾且不以 `ss` 结尾 ⇒ 复，否则 ⇒ 单
 *
 * 按最后一段而不是首段，是因为 `storage.backend.json` 这种键的单复数属于 `json` 这个后端名，
 * 不属于 `storage`。首段判法会把它读成「单」—— 碰巧对，但下一把叫 `storage.backend.series`
 * 就会读错。判据要跟着语义的承载位走。
 * @param key - ctx 键（不含 `ctx.` 前缀）。
 * @param form - 该键的声明形态（见 {@link scanSource}）；判断「是不是表单键」用它。
 */
function ctlgPluralityOf(key: string, form = ""): string {
  if (form.includes("hub 表单键")) return "表单"
  const seg = key.includes(".") ? (key.split(".").pop() ?? key) : key.split(/[A-Z]/)[0] || key
  return seg.endsWith("s") && !seg.endsWith("ss") ? "复" : "单"
}

/** 插件/类角色：只报**机器看得见的形态**，不猜角色词表。 */
function ctlgRoleOf(pkg: { serviceClasses?: string[]; hasApply?: boolean }): string {
  if (pkg.serviceClasses?.length) return `Service 子类 \`${pkg.serviceClasses.join("`、`")}\``
  if (pkg.hasApply) return "插件（`apply`）"
  return "库（无 `apply`、无 `Service` 子类）"
}

const ctlgCell = (s: unknown) => String(s).replace(/\|/g, "\\|")

/** 生成物一行：把 ctx 键 + 来源包 + 形态 + 位置拼成表格行。 */
function keyRowLine(r: CtxKey & { pkg: string }): string {
  return `| \`ctx.${ctlgCell(r.key)}\` | \`${ctlgCell(r.pkg)}\` | ${ctlgCell(r.form)} | \`${ctlgCell(r.site)}:${r.line}\` |`
}

interface RenderSurface {
  packages?: { name?: string; serviceClasses?: string[]; hasApply?: boolean }[]
  keyRows?: (CtxKey & { pkg: string })[]
  eventRows?: (CtxEvent & { pkg: string })[]
}

/**
 * 渲染 `docs/ctx-catalog.md` 全文（纯函数：输入 = {@link scanCtxSurface} 的产物）。
 * @param surface - 扫描结果。
 * @returns 生成物全文（含末尾换行）。
 */
export function renderCatalog(surface?: RenderSurface): string {
  const { packages = [], keyRows = [], eventRows = [] } = surface ?? {}
  const lines: string[] = []
  lines.push(HEADER, "")
  lines.push("# ctx catalog（生成物，勿手改）", "")
  lines.push(
    `包 ${packages.length} 个 · ctx 键 ${keyRows.length} 条 · 事件 ${eventRows.length} 条。` +
      "重生成：`node scripts/gen-ctx-catalog.ts`；新鲜度：`node scripts/gates/verify-ctx-catalog.ts --check`。",
    "",
  )
  lines.push(
    "本表由源码结构化解析得出，不按包名字面匹配 —— `@matter/storage` 是 `@matter/storage-journal` 的前缀，" +
      "字面匹配会把两者的声明混到一起。扫描面是 `packages/*/*/package.json` 与各包 `src/**/*.ts`；" +
      "`lib/` 是构建产物，不扫。",
    "",
  )
  lines.push(
    "「单/复」按 **键的形状**判（hub 表单键标「表单」；其余按最后一段：以 `s` 结尾且不以 `ss` 结尾判「复」）。" +
      "这是形状判据，不是角色定名 —— 角色词表（Store / Registry / Directory / …）要人工对，本表不猜。",
    "",
  )

  lines.push("## 包清单", "")
  lines.push("| 包名 | ctx key | 类角色 | 单复数 |")
  lines.push("|---|---|---|---|")
  for (const pkg of packages) {
    const mine = keyRows.filter((r) => r.pkg === pkg.name)
    const keys = mine.length ? mine.map((r) => `\`ctx.${r.key}\``).join("、") : "—"
    const plural = mine.length ? mine.map((r) => ctlgPluralityOf(r.key, r.form)).join("、") : "—"
    lines.push(`| \`${ctlgCell(pkg.name)}\` | ${ctlgCell(keys)} | ${ctlgCell(ctlgRoleOf(pkg))} | ${ctlgCell(plural)} |`)
  }
  lines.push("")

  lines.push("## ctx key 对照", "")
  lines.push("| ctx key | 来源包 | 形态 | 声明位置 |")
  lines.push("|---|---|---|---|")
  for (const r of [...keyRows].sort((a, b) => ctlgByCodeUnit(a.key, b.key) || ctlgByCodeUnit(a.pkg, b.pkg))) {
    lines.push(keyRowLine(r))
  }
  lines.push("")

  lines.push("## 事件清单", "")
  if (!eventRows.length) {
    lines.push("（无：本期没有任何包合并 `interface Events`）", "")
  } else {
    lines.push("| 事件名 | 模式 | 来源包 | 声明位置 |")
    lines.push("|---|---|---|---|")
    for (const e of [...eventRows].sort((a, b) => ctlgByCodeUnit(a.name, b.name) || ctlgByCodeUnit(a.pkg, b.pkg))) {
      lines.push(`| \`${ctlgCell(e.name)}\` | ${ctlgCell(e.mode ? `\`@mode ${e.mode}\`` : "—")} | \`${ctlgCell(e.pkg)}\` | \`${ctlgCell(e.site)}:${e.line}\` |`)
    }
    lines.push("")
  }

  return lines.join("\n")
}

/** 一次扫描 + 渲染（判据与 CLI 走同一条路，不许各写一份）。 */
export function buildCatalog(repo = REPO): string {
  return renderCatalog(scanCtxSurface(repo))
}

/**
 * ctx extractor 的数据面 = D0 `scanCtxSurface` 的产物（ISS-893 / 轨 D D1）。
 * 迁移**不改抽取与渲染逻辑**：仍走本文件已验的 `scanCtxSurface` / `renderCatalog`，
 * 故 `docs/ctx-catalog.md` 字节不变（6 包 / 7 键 / 1 事件）。`program` 由框架统一构建并传入，
 * 但 ctx 复用自己的 `createSourceFile`（setParentNodes + ScriptTarget.Latest，D0 的行号/JSDoc 口径）；
 * event / dependency 两个 extractor 直接用共享 program。
 */
export type CtxSurface = ReturnType<typeof scanCtxSurface>

/** 把 D0 生成器注册为框架的 ctx 消费者（3 个真实消费者之一）。 */
export const ctxExtractor: Extractor<CtxSurface> = {
  id: "ctx",
  output: OUT_REL,
  extract(repo) {
    return scanCtxSurface(repo)
  },
  render(data) {
    // D0 的 scanCtxSurface 产物与 RenderSurface 的宽松形状同构（packages 运行时无 null）；
    // buildCatalog 里已有同一种断言口径，这里对齐它，不新增类型放宽。
    return renderCatalog(data as Parameters<typeof renderCatalog>[0])
  },
}

function ctlgMain(argv: string[]): number {
  const check = argv.includes("--check")
  const target = path.join(REPO, OUT_REL)
  const text = buildCatalog(REPO)
  if (check) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null
    if (current === text) {
      console.log(`✓ ${OUT_REL} 与源码一致`)
      return 0
    }
    console.error(`✗ ${OUT_REL} ${current === null ? "不存在" : "是旧的"} —— 跑 \`node scripts/gen-ctx-catalog.ts\` 再提交`)
    return 1
  }
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, text)
  console.log(`✓ 已写 ${OUT_REL}（${text.length} B）`)
  return 0
}


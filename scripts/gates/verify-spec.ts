/**
 * 规范文档自审闸（ISS-742 / 计划 §5 G1-4）—— `docs/project-doc-rules.md` §4.1 的机器形态。
 *
 * 为什么要有它：§4.1 五条纪律（先正例后反例 / 规则与现状分层 / 一事一处 / 禁模糊词 / 与主题相符）
 * 写了半年全靠人工审；`code.md` 里成段的「当前 98 处」这类现状数字、指向已删脚本的指针、
 * 「变更记录」之后又长出来的正文，都是**人能看见但没人每次去看**的形态。这里只挑**可机检、低误报**的四条：
 *
 *   a) **悬空脚本指针**：文档里 `scripts/<x>.mjs|.ts` 的反引号引用，文件不存在 ⇒ 红（带行号）
 *
 *  ---------- (a) 的三种「不该报」形态（ISS-852）----------
 *  (a) 曾经把三类合法文档判成悬空，一刀切加宽正则会连真腐坏一起埋掉，所以逐类识别：
 *
 *   1. **上游语境** —— 行内含 `DSH` / `官方` / `上游` / `dsh-src`：引的是 DSH 官方实现的脚本，
 *      不在本仓 `scripts/` 下。⚠️ 只认大写 `DSH`，**刻意不加 `i` flag**：小写 `dsh` 是普通词
 *      （「dsh 这个词」），加 `i` 会把它后面真悬空的路径一起放过 —— 那是本判据唯一不能丢的牙。
 *   2. **HTML 注释文本** —— 两种形态，必须分别认：
 *      a. 整条注释在**反引号内**（`\`<!-- Generated by scripts/x.ts -->\``）：注释是**字面文本**，
 *         反引号优先于 HTML 注释，所以「行在注释内」的状态机**判不到它**，只能判 span 自身。
 *      b. 注释**跨行**把路径包住（`docs/layer-graph.md:1-3`）：反引号在注释里，反过来 a. 判不到。
 *         用跨行状态机；`<!-- ... --> \`scripts/x.ts\`` 这种行内闭合后**仍在注释外**，路径照报。
 *   3. **显式标记** —— 行内 `<!-- pending: 理由 -->`（待建）/ `<!-- official: 理由 -->`（引官方）。
 *      `pending` 的文件若已建 ⇒ **红**（否则标记自己会腐坏，与白名单「只提示不判红」同病）；
 *      标记那行没有任何 `scripts/...` 引用 ⇒ **红**（否则无法确定它豁免的是哪一条）。
 *
 *  两套标记而不用 `spec-ref: pending`：`pending:` 已是 mermaid 状态机的既有词汇
 *  （`specs/external-agent-dispatch-unified.md:78`、`specs/pm-members-agents-plan.md:291`），
 *  让它再承担「待建」语义 = 同一个词两处意思 = 第二个真相源。HTML 注释前缀 `<!--` 才是唯一的。
 *   b) **现状数字句式**：`当前 N 个` / `已 N 处` / `现在有 N` / `共 N 个` ⇒ 红（§4.1 ②：规范不写现状）
 *   c) **编号重复**：同一文档内 `K\d+[a-z]?` 主条、`REV-\d+` 重复定义 ⇒ 红（§4.1 ③：一事一处）
 *   d) **「变更记录」之后不得再有正文**：首个 `^## *变更记录` 之后又出现 `##` 且标题不含「变更记录」⇒ 红
 *
 * 三条**刻意不判**（写在这里免得下一个人以为是漏了）：
 *   · 「合理 / 适当 / 尽量」等模糊词 —— 正常行文里也大量出现，机检必然高误报，留人审
 *   · 「先正例后反例」的**顺序** —— 只能靠语义判，段落结构不是机检对象
 *   · 「K 号是否悬空指向已退役判据」 —— 属于 G3 退役面，不是写作纪律
 *
 * 判据口径（`scripts/lib/gate-runtime.ts`）：0 绿 / 1 红 / 2 判不了。
 *   **白名单文件缺失 ≠ 判不了**：按空白名单照判（缺文件不能把整格变成不可判）。
 *   **扫描面为空**才是判不了（`no-corpus`）。
 *   白名单每条必须带 `why`；`why` 为空 ⇒ 该条不生效，命中的问题照红。
 */

/**
 * 行内分段：表格行按未转义的 `|` 切段，其余整行一段。
 *
 * 为什么要分段：**上游词是「引用」的修饰语，不是整行的标签**。
 * `matter-v2-refactor-spec-2026-09-25.md:110` 实测踩中 —— 该行是表格，
 * 左格写「命令数 == **DSH** 工具数 == MCP 工具数」（讲的是工具计数），
 * 右格才是 `scripts/matter-contract-check.mjs`。按整行判 `DSH` ⇒ 右格那条待建脚本被静默吞掉，
 * 白名单从「命中并豁免」变成「不再命中」= 判据变窄。
 */
function segmentAt(raw: string, offset: number): string {
  let start = 0
  let p = 0
  while (p < offset && p < raw.length) {
    if (raw[p] === "\\") { p += 2; continue }
    if (raw[p] === "|") start = p + 1
    p++
  }
  let end = raw.length
  p = Math.min(offset, raw.length)
  while (p < raw.length) {
    if (raw[p] === "\\") { p += 2; continue }
    if (raw[p] === "|") { end = p; break }
    p++
  }
  return raw.slice(start, end)
}


/**
 * `verify-field-catalog` 的 spec（ISS-896 / P3-F1）。经 `--selftest` 被 gate-runtime 动态加载。
 *
 * 覆盖四件事，缺一条这条判据就没有牙：
 *   ① 正例：生成物与现算一致 ⇒ passed（含真语料 scan()）
 *   ② **必然失败**的用例：改一个字符 / 删文件 / 改文件头各断言 failed，且点名到文件与行、
 *      文案含「跑生成器」与能直接粘的重生成命令
 *   ③ 判不了的用例：0 张 schema ⇒ unjudged（⛔ 不许绿 —— 空表与空表当然一致）
 *   ④ 同口径：expected 来自生成器 buildFieldCatalog（判据不另写扫描）
 */
import assert from "node:assert/strict"
import { judgeFieldCatalog, scan, type FieldCatalogInput } from "./verify-field-catalog.ts"
import { REPO, buildFieldCatalog } from "../gen-field-catalog.ts"

let fails = 0
let pass = 0
const ok = (name: string, cond: boolean, extra?: string) => {
  console.log(`  ${cond ? "✓" : "✗"} ${name}${!cond && extra ? ` —— ${extra}` : ""}`)
  if (cond) pass++
  else fails++
}

/** 最小可用样本：一张真语料规模的输入（actual = expected ⇒ 一致），只为了让断言读得懂。 */
function fixture(): FieldCatalogInput {
  const expected = "<!-- Generated by scripts/gen-field-catalog.ts — do not edit by hand. -->\n# field catalog\n（略）"
  return { actual: expected, expected, schemaCount: 3 }
}

export function run(): boolean {
  fails = 0
  pass = 0

  const good = judgeFieldCatalog(fixture())
  ok("正例① 一致 ⇒ passed", good.status === "passed", good.status)

  // 反例① 改一个字符（尾行）：必须红、点名文件与行、文案含「跑生成器」与重生成命令
  const mutated = fixture()
  mutated.actual = `${mutated.actual}-CHANGED`
  const m = judgeFieldCatalog(mutated)
  ok(
    "反例① 改一个字符 ⇒ failed 且点名文件/行 + 「跑生成器」+ 重生成命令",
    m.status === "failed" &&
      m.findings?.some((f) => f.file === "docs/field-catalog.md" && f.line === 3 && /内容与源码不一致/.test(f.detail)) === true &&
      m.findings?.some((f) => /跑生成器 `node scripts\/gen-field-catalog\.ts`/.test(f.detail)) === true,
    `${m.status} / ${JSON.stringify(m.findings)}`,
  )

  // 反例② 文件缺失：必须红，且说清「生成物进 git」
  const missing = fixture()
  missing.actual = null
  const ms = judgeFieldCatalog(missing)
  ok(
    "反例② 文件不存在 ⇒ failed 且文案含「跑生成器」与「提交进 git」",
    ms.status === "failed" &&
      ms.findings?.some((f) => f.file === "docs/field-catalog.md" && /跑生成器/.test(f.detail) && /提交进 git/.test(f.detail)) === true,
    `${ms.status} / ${JSON.stringify(ms.findings)}`,
  )

  // 反例③ 改文件头：必须红并指到第 1 行
  const hdr = fixture()
  hdr.actual = `TAMPERED\n# field catalog\n（略）`
  const h = judgeFieldCatalog(hdr)
  ok(
    "反例③ 改文件头 ⇒ failed 且指到第 1 行",
    h.status === "failed" && h.findings?.some((f) => f.file === "docs/field-catalog.md" && f.line === 1 && /文件头/.test(f.detail)) === true,
    `${h.status} / ${JSON.stringify(h.findings)}`,
  )

  // 判不了：0 张 schema 不许绿
  const noCorpus = fixture()
  noCorpus.schemaCount = 0
  const u = judgeFieldCatalog(noCorpus)
  ok("判不了① 0 张 schema ⇒ unjudged(no-corpus)，不冒充绿", u.status === "unjudged" && u.reason === "no-corpus", `${u.status}/${u.reason}`)

  // 集成正例：真语料 scan() 与 committed 生成物一致
  const live = scan()
  ok("正例② 真语料扫到 3 张 schema（committed 生成物与源码一致）", live.schemaCount === 3 && live.actual === live.expected, `${live.schemaCount}/${live.actual === live.expected}`)
  const liveJudge = judgeFieldCatalog(live)
  ok("正例③ 真语料判 passed", liveJudge.status === "passed", `${liveJudge.status} / ${JSON.stringify(liveJudge.findings)}`)

  // 有牙：真语料注入多余行 ⇒ 必红
  const teethInput = scan()
  teethInput.actual = `${teethInput.expected}\n多一行`
  const teeth = judgeFieldCatalog(teethInput)
  ok("反例④ 真语料注入多余行 ⇒ failed（判据有牙）", teeth.status === "failed", teeth.status)

  // 同口径：expected 与生成器逐字相同（判据不另写扫描）
  ok("不变式：判据的 expected 与生成器 buildFieldCatalog 逐字相同", scan().expected === buildFieldCatalog(REPO))

  const total = pass + fails
  if (fails) {
    console.error(`✗ verify-field-catalog spec：${pass} 过 / ${fails} 失败（SPEC_RESULT total=${total} pass=${pass} fail=${fails}）`)
    return false
  }
  console.log(`✓ verify-field-catalog spec 全过：${total} 条（SPEC_RESULT total=${total} pass=${pass} fail=${fails}）`)
  return true
}

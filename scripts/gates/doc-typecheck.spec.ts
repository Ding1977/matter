/**
 * `doc-typecheck` 的 spec（ISS-894）。入口 `--selftest`（gate-runtime 动态加载约定），非 vitest。
 *
 * 5 个变异用例（老板指定，必须有牙）：
 *   ① in-scope 坏 fence ⇒ 红带 文件:行 + 期望/实际
 *   ② 无理由 ignore ⇒ 红
 *   ③ 空语料 ⇒ unjudged（不冒绿）
 *   ④ 生成头注文件坏 fence ⇒ 不红（文件级 skip）
 *   ⑤ dsh-wiki 坏 fence ⇒ 不红（射程隔离）
 *
 * ④⑤ 各配一条**正向对照**：同一段坏 fence 放进 in-scope 文件必须红 —— 否则「不红」可能只是
 * 判据没牙，不是 skip/射程生效（说「一样」必须给出「不一样会是什么样」）。
 */
import { collectBlocks, compileStandalone, isInScope, judge, remapBlockPaths, scanFences, type CompileFn } from "./doc-typecheck.ts"

let fails = 0
const ok = (name: string, cond: boolean, extra?: string) => {
  console.log(`  ${cond ? "✓" : "✗"} ${name}${!cond && extra ? ` —— ${extra}` : ""}`)
  if (!cond) fails++
}

/** 恒返回一条 TS 错的假编译器：让 judge 的判红路径可构造，不依赖真实构建。 */
const badCompile: CompileFn = (blocks) => ({
  kind: "errors",
  errors: blocks.map((b, i) => ({ file: b.file, line: b.line + 1, column: 1, message: `TS2304: test error ${i}` })),
})
/** 恒绿的假编译器：验「带理由 ignore 只打印不判红」。 */
const goodCompile: CompileFn = () => ({ kind: "compiled" })

const BAD_FENCE = "```ts\nconst x = missingName\n```\n"

export function run(): boolean {
  fails = 0
  console.log("doc-typecheck.spec")

  // 扫描器：行号 + info string + 代码体（零新依赖的行扫描器本身要被验）
  {
    const f = scanFences(`before\n${BAD_FENCE}after\n`)
    ok("扫描器：认出 ts fence 与开栏行号", f.length === 1 && f[0].line === 2 && f[0].info === "ts", JSON.stringify(f))
    ok("扫描器：代码体不含围栏", f[0]?.code.trim() === "const x = missingName", f[0]?.code)
  }

  // isInScope：白名单与三个排除项
  {
    ok("射程：自有 docs 在射程内", isInScope("docs/design.md"))
    ok("射程：包 README 在射程内", isInScope("packages/storage/storage/README.md"))
    ok("射程：dsh-wiki 排除", !isInScope("docs/dsh-wiki/08-extension-points.md"))
    ok("射程：memory 排除", !isInScope("docs/memory/dsh-gates-alignment.md"))
    ok("射程：.zh.md 配对副本排除", !isInScope("packages/storage/storage/README.zh.md"))
  }

  // ── ① in-scope 坏 fence ⇒ 红带 文件:行 + 期望/实际 ─────────────
  {
    const s = collectBlocks(["docs/api.md"], () => BAD_FENCE)
    const r = judge({ ...s, compile: badCompile })
    const detail = (r.findings ?? []).map((f) => f.detail).join(" ")
    ok("① in-scope 坏 fence ⇒ failed", r.status === "failed", `实际 ${r.status}`)
    ok("① 红带 文件:行", (r.findings ?? []).some((f) => f.file === "docs/api.md" && f.line === 2), JSON.stringify(r.findings))
    ok("① 红带 期望与实际", detail.includes("期望") && detail.includes("实际"), detail)
  }

  // ── ② 无理由 ignore ⇒ 红；带理由 ignore 不红 ────────────────────
  {
    const s = collectBlocks(["docs/api.md"], () => "```ts ignore-check\nconst x = sketch\n```\n")
    const r = judge({ ...s, compile: badCompile })
    ok("② 无理由 ignore ⇒ failed", r.status === "failed", `实际 ${r.status}`)
    ok("② 红点名无理由与文件:行", (r.findings ?? []).some((f) => f.file === "docs/api.md" && f.line === 1 && f.detail.includes("无理由")))
  }
  {
    const s = collectBlocks(["docs/api.md"], () => "```ts ignore-check: 外部 API 草稿\nconst x = sketch\n```\n")
    ok("② 带理由 ignore 不是 finding", s.badIgnores.length === 0 && s.blocks[0]?.kind === "ignore", JSON.stringify(s))
    const r = judge({ ...s, compile: goodCompile })
    ok("② 带理由 ignore 只打印不判红（注入编译器）", r.status === "passed", `实际 ${r.status}`)
  }
  {
    // F2 真路径：不用注入，100% 带理由 opt-out 的 checked 为空，走真实 compileStandalone 不得判红
    // （否则 tsc 的 TS18003「No inputs were found」会把显式跳过误伤成失败）。
    const s = collectBlocks(["docs/api.md"], () => "```ts ignore-check: 外部 API 草稿\nconst x = sketch\n```\n")
    const outcome = compileStandalone([])
    const real = judge({ ...s, compile: compileStandalone })
    ok("② 真路径：空 blocks 的 compileStandalone ⇒ compiled 且全理由 opt-out 不判红",
      outcome.kind === "compiled" && real.status !== "failed",
      `outcome=${outcome.kind} judge=${real.status}`)
  }

  // ── ③ 空语料 ⇒ unjudged（不冒绿） ─────────────────────────────
  {
    const r = judge({ blocks: [], badIgnores: [], skippedGenerated: 0, compile: badCompile })
    ok("③ 空语料 ⇒ unjudged(no-corpus)", r.status === "unjudged" && r.reason === "no-corpus", `实际 ${r.status}/${r.reason}`)
  }

  // ── ④ 生成头注文件坏 fence ⇒ 不红（文件级 skip）+ 正向对照 ──────
  {
    const gen = "<!-- Generated by scripts/gen-x.ts — do not edit by hand. -->\n" + BAD_FENCE
    const s = collectBlocks(["docs/catalog.md"], () => gen)
    ok("④ 头注文件整文件跳过", s.skippedGenerated === 1 && s.blocks.length === 0, JSON.stringify(s))
    const r = judge({ ...s, compile: badCompile })
    ok("④ 头注文件坏 fence ⇒ 不红", r.status !== "failed", `实际 ${r.status}`)
    // 正向对照：同一段 fence 放进 in-scope 文件必须红。
    const ctrl = collectBlocks(["docs/api.md"], () => gen.replace(/^<!--.*-->\n/, ""))
    ok("④ 正向对照：同 fence 在 in-scope ⇒ 红", judge({ ...ctrl, compile: badCompile }).status === "failed")
  }

  // ── ⑤ dsh-wiki 坏 fence ⇒ 不红（射程隔离）+ 正向对照 ───────────
  {
    const s = collectBlocks(["docs/dsh-wiki/08-extension-points.md"], () => BAD_FENCE)
    ok("⑤ dsh-wiki 不在射程", s.blocks.length === 0, JSON.stringify(s))
    const r = judge({ ...s, compile: badCompile })
    ok("⑤ dsh-wiki 坏 fence ⇒ 不红", r.status !== "failed", `实际 ${r.status}`)
    const ctrl = collectBlocks(["docs/api.md"], () => BAD_FENCE)
    ok("⑤ 正向对照：同 fence 在 in-scope ⇒ 红", judge({ ...ctrl, compile: badCompile }).status === "failed")
  }

  // ── 缺构建产物 ⇒ unjudged 不判红（三态门的第三态） ───────────────
  {
    const s = collectBlocks(["docs/api.md"], () => BAD_FENCE)
    const r = judge({ ...s, compile: () => ({ kind: "no-build", detail: "no lib" }) })
    ok("no-build ⇒ unjudged 不判红", r.status === "unjudged" && r.reason === "no-build", `实际 ${r.status}/${r.reason}`)
  }

  // ── remapBlockPaths：虚拟路径回指 Markdown 文件:行 ─────────────
  {
    const s = collectBlocks(["docs/api.md"], () => BAD_FENCE)
    const mapped = remapBlockPaths("block-0.ts(1,5): error TS2304: x", s.blocks)
    ok("remap：block-0.ts(1,5) → docs/api.md:2:5", mapped.startsWith("docs/api.md:2:5"), mapped)
  }

  console.log(`doc-typecheck.spec: ${fails === 0 ? "ALL PASS" : `${fails} FAILED`}`)
  return fails === 0
}
